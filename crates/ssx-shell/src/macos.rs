/// The shell script Automator runs; the selected files arrive as `"$@"`.
pub(crate) fn shell_script(ctx: &Context, a: &Action) -> Result<String> {
    let exe = sh_word(ctx.exe_str()?);
    let args: Vec<String> = a.exec_args.iter().map(|x| sh_word(x)).collect();
    let args = args.join(" ");
    Ok(if a.multi_select {
        format!("exec {exe} {args} -- \"$@\"\n")
    } else {
        format!("for f in \"$@\"; do\n    {exe} {args} -- \"$f\"\ndone\n")
    })
}

/// `Contents/document.wflow` for one action.
pub(crate) fn document_wflow(ctx: &Context, a: &Action) -> Result<String> {
    let script = xml_escape(&shell_script(ctx, a)?);
    let action_uuid =
        guid_for(&format!("ssx-shell:wflow:action:{}", a.id)).trim_matches(['{', '}']).to_owned();
    let input_uuid =
        guid_for(&format!("ssx-shell:wflow:input:{}", a.id)).trim_matches(['{', '}']).to_owned();
    let output_uuid =
        guid_for(&format!("ssx-shell:wflow:output:{}", a.id)).trim_matches(['{', '}']).to_owned();
    Ok(WFLOW_TEMPLATE
        .replace("@@PLIST_HEAD@@", PLIST_HEAD)
        .replace("@@MARKER@@", MARKER)
        .replace("@@SCRIPT@@", &script)
        .replace("@@UUID@@", &action_uuid)
        .replace("@@INPUT_UUID@@", &input_uuid)
        .replace("@@OUTPUT_UUID@@", &output_uuid))
}

