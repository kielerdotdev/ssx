//! Finder Quick Actions: Automator workflow bundles in `~/Library/Services`.
//!
//! A Quick Action is a `<name>.workflow` bundle with two files that we generate as text:
//! `Contents/Info.plist` (declares the Services menu entry: `NSServices`, `NSSendFileTypes`)
//! and `Contents/document.wflow` (the Automator workflow: a single "Run Shell Script" action
//! receiving the selected files **as arguments**, so `"$@"` is the exact list of POSIX paths).
//! Finder shows them under right-click > Quick Actions (and Services).
//!
//! **Not verified on a real Mac**: the plist structure follows what Automator writes for a
//! "Quick Action / files or folders in Finder" workflow and is validated here only for
//! well-formedness, golden output and script behaviour. After installing, `pbs -update` asks
//! the Services daemon to rescan; the user may still have to enable the entries in
//! System Settings > Keyboard > Keyboard Shortcuts > Services > Files and Folders (or
//! System Settings > Extensions > Finder).

use std::path::PathBuf;

use crate::action::{Action, FilterKind};
use crate::context::{Context, Platform};
use crate::error::{Result, ShellError};
use crate::fsutil::{MARKER, ManagedFile, files_current, install_files, uninstall_files};
use crate::integration::{Description, Detection, InstallOutcome, Integration, UninstallOutcome};
use crate::quote::{sh_word, xml_escape};
use crate::windows::manifest::guid_for;

const PBS: &str = "/System/Library/CoreServices/pbs";

/// Finder Quick Actions integration.
#[derive(Debug, Clone, Copy, Default)]
pub struct QuickActions;

impl QuickActions {
    /// Creates the integration.
    pub fn new() -> Self {
        Self
    }

    fn bundle(ctx: &Context, a: &Action) -> PathBuf {
        ctx.home.join("Library").join("Services").join(format!("{}.workflow", a.label))
    }

    fn files(ctx: &Context) -> Result<Vec<ManagedFile>> {
        let mut files = Vec::new();
        for a in &ctx.actions {
            if a.label.contains(['/', ':']) || a.label.starts_with('.') {
                return Err(ShellError::InvalidAction {
                    id: a.id.clone(),
                    reason: "Quick Action bundles are named after the label, which must not contain '/' or ':' or start with '.'".into(),
                });
            }
            let contents = Self::bundle(ctx, a).join("Contents");
            files.push(ManagedFile::new(contents.join("Info.plist"), info_plist(a), 0o644));
            files.push(ManagedFile::new(
                contents.join("document.wflow"),
                document_wflow(ctx, a)?,
                0o644,
            ));
        }
        Ok(files)
    }

    fn refresh(ctx: &Context) {
        if let Err(e) = ctx.runner.run(PBS, &["-update".to_owned()]) {
            tracing::debug!(error = %e, "pbs -update not run");
        }
    }
}

impl Integration for QuickActions {
    fn id(&self) -> &'static str {
        "macos-quick-actions"
    }

    fn name(&self) -> &'static str {
        "Finder Quick Actions"
    }

    fn platform(&self) -> Platform {
        Platform::MacOs
    }

    fn detect(&self, _ctx: &Context) -> Detection {
        Detection::found("Finder")
    }

    fn install(&self, ctx: &Context) -> Result<InstallOutcome> {
        let outcome = install_files(&Self::files(ctx)?)?;
        if outcome != InstallOutcome::AlreadyPresent {
            Self::refresh(ctx);
        }
        Ok(outcome)
    }

    fn uninstall(&self, ctx: &Context) -> Result<UninstallOutcome> {
        let outcome = uninstall_files(&Self::files(ctx)?, ctx)?;
        if outcome == UninstallOutcome::Removed {
            Self::refresh(ctx);
        }
        Ok(outcome)
    }

    fn is_installed(&self, ctx: &Context) -> Result<bool> {
        files_current(&Self::files(ctx)?)
    }

    fn describe(&self, ctx: &Context) -> Description {
        let paths: Vec<PathBuf> = ctx.actions.iter().map(|a| Self::bundle(ctx, a)).collect();
        Description::paths("macos-quick-actions", "Finder Quick Actions (right-click > Quick Actions)", &paths)
            .note("runs `pbs -update` so Finder notices the new services")
            .note("if an entry is missing, enable it under System Settings > Keyboard > Keyboard Shortcuts > Services > Files and Folders")
    }
}

fn uti_for(a: &Action) -> &'static str {
    match a.filter.kind {
        FilterKind::Images => "public.image",
        FilterKind::Videos => "public.movie",
        FilterKind::Any | FilterKind::Custom => "public.item",
    }
}

